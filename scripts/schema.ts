import { readFile, writeFile } from 'node:fs/promises';
import { startDatabase } from '../tests/database-harness.js';

// Generate only structural metadata from a disposable synthetic cluster, never the remote project.
const db = await startDatabase();
try {
  const columns = (
    await db.owner
      .query(`select c.relname as name,a.attname as column,format_type(a.atttypid,a.atttypmod) as type,a.attnotnull as required
    from pg_attribute a join pg_class c on c.oid=a.attrelid where c.relnamespace='academy'::regnamespace and c.relkind='r' and a.attnum>0 and not a.attisdropped order by c.relname,a.attnum`)
  ).rows;
  const constraints = (
    await db.owner
      .query(`select c.relname as name,pg_get_constraintdef(con.oid) as definition from pg_constraint con join pg_class c on c.oid=con.conrelid
    where c.relnamespace='academy'::regnamespace order by c.relname,con.contype,con.conname`)
  ).rows;
  const tables = [...new Set<string>(columns.map((c) => c.name))];
  const lines = [
    '# Application data dictionary',
    '',
    `Generated by \`npm run docs:schema\` from the six migrations in an empty PostgreSQL 17 cluster. ${tables.length} tables in the unexposed \`academy\` schema; zero student fixtures in the migrations.`,
    '',
    'Each column is `name: type`; `?` means nullable. Key, relationship and check definitions below come from the PostgreSQL catalog. The migration files additionally specify defaults, indexes, domains, triggers and privileges. Application UUIDs are independent of external account IDs. `auth.users`, `storage.buckets` and `storage.objects` are managed by Supabase, not application tables.',
    '',
    'See [modules and relationships](architecture.md) and the [access matrix](security-operations.md). Do not expose this schema to PostgREST.',
    '',
  ];
  for (const table of tables) {
    lines.push(
      '## `' + table + '`',
      '',
      columns
        .filter((c) => c.name === table)
        .map((c) => '`' + c.column + ': ' + c.type + (c.required ? '' : '?') + '`')
        .join(', '),
      '',
    );
    for (const c of constraints.filter((c) => c.name === table))
      lines.push('- `' + c.definition + '`');
    lines.push('');
  }
  const rendered = lines.join('\n');
  const path = 'docs/data-dictionary.md';
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== rendered)
      throw new Error('Stale schema dictionary: run npm run docs:schema');
  } else await writeFile(path, rendered);
} finally {
  await db.stop();
}
