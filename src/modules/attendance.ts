import { z } from 'zod';
import { id, day, time, page, idResult, states, type Contract } from '../platform/contract.js';
const token = z.string().regex(/^[0-9a-f]{64}$/);
export const attendance: Contract[] = [
  {
    method: 'POST',
    path: '/cards/issue',
    rpc: 'issue_card',
    summary: 'Issue a QR once; replace=true revokes the old token atomically',
    access: 'card.issue',
    body: z.strictObject({ student_id: id, expires_at: time, replace: z.boolean().default(false) }),
    status: 201,
    result: z.object({ card_id: id, qr_token: token, print_job_id: id, expires_at: time }),
  },
  {
    method: 'POST',
    path: '/cards/revoke',
    rpc: 'revoke_card',
    summary: 'Revoke a card and cancel pending prints',
    access: 'card.issue',
    body: z.strictObject({ card_id: id }),
    result: idResult,
  },
  {
    method: 'GET',
    path: '/cards/{card_id}/print',
    rpc: 'print_metadata',
    params: { card_id: id },
    summary: 'Read current card print metadata only (no QR retrieval or rendering)',
    access: 'card.issue',
    result: z.object({
      card_id: id,
      student_code: z.string(),
      name: z.string(),
      grade: z.number(),
      expires_at: time,
    }),
  },
  {
    method: 'GET',
    path: '/students/{student_id}/cards',
    rpc: 'cards',
    params: { student_id: id },
    summary: 'Read card metadata; expiry evaluated using server time',
    access: 'family or card.issue',
    result: z.array(z.object({ id, status: z.string(), issued_at: time, expires_at: time })),
  },
  {
    method: 'POST',
    path: '/attendance/scan',
    rpc: 'scan',
    summary: 'Record a supervised scan; retry identical requests with the same request_id',
    access: 'attendance.scan + active device assigned to operator and class',
    body: z.strictObject({ device_id: id, session_id: id, request_id: id, qr_token: token }),
    result: z.object({
      result: z.enum([
        'present',
        'late',
        'duplicate',
        'invalid_card',
        'outside_window',
        'not_enrolled',
      ]),
      attendance_id: id.nullable(),
    }),
  },
  {
    method: 'POST',
    path: '/attendance/override',
    rpc: 'correct_attendance',
    summary: 'Correct or manually mark attendance with an immutable reason',
    access: 'attendance.correct + assigned class or academic.all',
    body: z.strictObject({
      session_id: id,
      student_id: id,
      status: states,
      reason: z.string().trim().min(3).max(400),
    }),
    result: idResult,
  },
  {
    method: 'GET',
    path: '/attendance/reports',
    rpc: 'report',
    summary: 'Daily session roster in Asia/Colombo, optionally filtered to one class',
    access: 'attendance.report + class scope',
    query: { day, group_id: id.nullable().default(null), ...page },
    result: z.array(
      z.object({
        group_id: id,
        session_id: id,
        student_id: id,
        student_code: z.string(),
        name: z.string(),
        status: z.enum([...states.options, 'unmarked']),
      }),
    ),
  },
  {
    method: 'GET',
    path: '/students/{student_id}/attendance',
    rpc: 'history',
    summary: 'Student attendance history',
    access: 'family or scoped reporting staff',
    params: { student_id: id },
    query: page,
    result: z.array(
      z.object({
        id,
        session_id: id,
        status: states,
        marked_at: time,
        source: z.enum(['manual', 'scan']),
      }),
    ),
  },
];
