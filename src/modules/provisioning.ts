import { z } from 'zod';
import { id, text, time, idResult, type Contract } from '../platform/contract.js';
export const provisioning: Contract[] = [
  {
    method: 'POST',
    path: '/admin/courses',
    rpc: 'create_course',
    summary: 'Create a grade 6–11 course',
    access: 'schedule.manage',
    body: z.strictObject({ grade: z.number().int().min(6).max(11), title: text }),
    status: 201,
    result: idResult,
  },
  {
    method: 'POST',
    path: '/admin/classes',
    rpc: 'create_class',
    summary: 'Assign a verified staff-role teacher to a course group',
    access: 'schedule.manage',
    body: z.strictObject({ course_id: id, label: text, teacher_id: id }),
    status: 201,
    result: idResult,
  },
  {
    method: 'POST',
    path: '/admin/sessions',
    rpc: 'schedule',
    summary: 'Set a class time, scan window (maximum 24 hours) and lateness threshold',
    access: 'schedule.manage',
    body: z.strictObject({
      group_id: id,
      starts_at: time,
      ends_at: time,
      scan_opens_at: time,
      scan_closes_at: time,
      late_after: time,
    }),
    status: 201,
    result: idResult,
  },
  {
    method: 'POST',
    path: '/admin/devices',
    rpc: 'register_device',
    summary: 'Register a supervised scanner for an authorized operator and class',
    access: 'device.manage',
    body: z.strictObject({ label: text, location: text, operator_id: id, group_id: id }),
    status: 201,
    result: idResult,
  },
  {
    method: 'POST',
    path: '/admin/devices/{device_id}/disable',
    rpc: 'disable_device',
    summary: 'Disable a registered scanner',
    access: 'device.manage',
    params: { device_id: id },
    result: idResult,
  },
];
